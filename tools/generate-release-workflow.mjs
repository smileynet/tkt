#!/usr/bin/env node
// Project cargo-dist's generated build jobs into a manual, nonpublishing workflow.
// Usage: node tools/generate-release-workflow.mjs [--write]
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseToml, stringify as toml } from "smol-toml";
import { parse as parseYaml, stringify as yaml } from "yaml";
import { ReleaseError } from "./release-version.mjs";
import { gitEnvironment } from "./release-git.mjs";
const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const identitySteps = () => [
  { uses: "actions/setup-node@v7", with: { "node-version": "22", "package-manager-cache": false } },
  { name: "Install locked maintainer dependencies", run: "npm ci --ignore-scripts --no-audit --no-fund" },
  { name: "Verify candidate identity", id: "identity", run: "node tools/release-ci.mjs identity", env: { EXPECTED_CANDIDATE_SHA: "${{ inputs.candidate_sha }}" } },
];
const checkout = { uses: "actions/checkout@v6", with: { "persist-credentials": false } };
export function stageWorkflow(generated) {
  const raw = parseYaml(generated);
  if (Object.keys(raw.jobs).sort().join(",") !== "announce,build-global-artifacts,build-local-artifacts,host,plan") throw new ReleaseError("unreviewed cargo-dist job topology");
  const jobs = Object.fromEntries(["plan", "build-local-artifacts", "build-global-artifacts"].map((name) => [name, raw.jobs[name]]));
  for (const job of Object.values(jobs)) {
    delete job.env?.GH_TOKEN;
    const index = job.steps.findIndex((step) => step.uses?.startsWith("actions/checkout@"));
    if (index < 0) throw new ReleaseError("generated build job is missing its checkout");
    job.steps.splice(index + 1, 0, ...identitySteps());
    for (const step of job.steps) {
      if (step.uses?.startsWith("actions/download-artifact@")) {
        step.with["digest-mismatch"] = "error";
        const key = step.with.name ? "name" : "pattern";
        step.with[key] += "-attempt-${{ github.run_attempt }}";
      }
      if (step.uses?.startsWith("actions/upload-artifact@")) {
        step.with["if-no-files-found"] = "error";
        step.with.name += "-attempt-${{ github.run_attempt }}";
      }
    }
  }
  jobs.plan.outputs.tag = "${{ steps.identity.outputs.tag }}";
  jobs.plan.outputs["tag-flag"] = "${{ format('--tag={0}', steps.identity.outputs.tag) }}";
  jobs.plan.outputs.publishing = "false";
  const plan = jobs.plan.steps.find((step) => step.id === "plan");
  if (!plan?.run?.includes("host --steps=create")) throw new ReleaseError("unreviewed cargo-dist plan command");
  plan.env = { CANDIDATE_TAG: "${{ steps.identity.outputs.tag }}" };
  plan.run = 'dist plan --tag "$CANDIDATE_TAG" --output-format=json > plan-dist-manifest.json\necho "manifest=$(jq -c . plan-dist-manifest.json)" >> "$GITHUB_OUTPUT"\n';
  jobs["build-local-artifacts"].if = "${{ fromJson(needs.plan.outputs.val).ci.github.artifacts_matrix.include != null }}";
  jobs["build-crate"] = {
    needs: ["plan"], "runs-on": "ubuntu-22.04", steps: [checkout, ...identitySteps(),
      { uses: "dtolnay/rust-toolchain@stable" },
      { name: "Build and verify clean source crate", run: "cargo package --locked --target-dir target/crate-stage" },
      { uses: "actions/upload-artifact@v7", with: { name: "artifacts-crate-attempt-${{ github.run_attempt }}", path: "target/crate-stage/package/*.crate", "if-no-files-found": "error" } },
    ],
  };
  jobs["seal-stage"] = {
    needs: ["plan", "build-local-artifacts", "build-global-artifacts", "build-crate"], "runs-on": "ubuntu-22.04",
    steps: [checkout, ...identitySteps(),
      { uses: "actions/download-artifact@v8", with: { pattern: "artifacts-*-attempt-${{ github.run_attempt }}", path: "target/stage-input", "merge-multiple": true, "digest-mismatch": "error" } },
      { name: "Seal exact built files", run: "node tools/release-ci.mjs collect target/stage-input target/sealed-stage", env: { EXPECTED_CANDIDATE_SHA: "${{ inputs.candidate_sha }}" } },
      { uses: "actions/upload-artifact@v7", with: { name: "tkt-sealed-stage-${{ github.run_id }}-${{ github.run_attempt }}", path: "target/sealed-stage/*", "if-no-files-found": "error" } },
    ],
  };
  const workflow = { name: "Stage release artifacts", on: { workflow_dispatch: { inputs: { candidate_sha: { description: "Exact reviewed candidate commit (40 lowercase hex)", required: true, type: "string" } } } }, permissions: { contents: "read" }, jobs };
  const result = yaml(workflow, { lineWidth: 0 });
  if (/dist host|gh release|cargo publish|git push|contents: write|secrets\.(?!GITHUB_TOKEN)/.test(result)) throw new ReleaseError("publication path remains in staging workflow");
  return "# Generated by tools/generate-release-workflow.mjs from cargo-dist 0.32.0. Do not edit.\n" + result;
}
export function generateStageWorkflow(source = repo) {
  if (execFileSync("dist", ["--version"], { encoding: "utf8" }).trim() !== "cargo-dist 0.32.0") throw new ReleaseError("install cargo-dist 0.32.0 before generating release CI");
  // cargo-dist cannot discover workspaces through Windows 8.3 path aliases.
  const temp = realpathSync.native(mkdtempSync(join(tmpdir(), "tkt dist generation ")));
  try {
    for (const file of ["Cargo.toml", "Cargo.lock", "build.rs", "src", "README.md", "CHANGELOG.md", "LICENSE"]) cpSync(join(source, file), join(temp, file), { recursive: true });
    const config = parseToml(readFileSync(join(temp, "Cargo.toml"), "utf8"));
    if (config.package.name !== "tkt" || config.workspace.metadata.dist["cargo-dist-version"] !== "0.32.0") throw new ReleaseError("unreviewed product or dist version");
    config.workspace.metadata.dist["allow-dirty"] = [];
    writeFileSync(join(temp, "Cargo.toml"), toml(config));
    const git = (...args) => execFileSync("git", ["-C", temp, ...args], { env: gitEnvironment(), stdio: "pipe" });
    git("init"); git("remote", "add", "origin", "https://github.com/smileynet/tkt.git"); git("add", ".");
    git("-c", "user.name=Generation fixture", "-c", "user.email=fixture@example.invalid", "-c", `core.hooksPath=${join(temp, "no-hooks")}`, "commit", "-m", "Generation inputs");
    execFileSync("dist", ["generate", "--mode", "ci"], { cwd: temp, env: gitEnvironment(), stdio: "pipe" });
    return stageWorkflow(readFileSync(join(temp, ".github/workflows/release.yml"), "utf8"));
  } finally { rmSync(temp, { recursive: true, force: true }); }
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2); if (args.some((arg) => arg !== "--write") || args.length > 1) throw new ReleaseError("usage: generate-release-workflow.mjs [--write]");
    const expected = generateStageWorkflow(), path = join(repo, ".github/workflows/release.yml"), write = args.includes("--write");
    if (write) { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, expected); }
    else if (!existsSync(path) || readFileSync(path, "utf8") !== expected) throw new ReleaseError("release workflow differs; run node tools/generate-release-workflow.mjs --write");
    console.log(JSON.stringify({ status: "pass", mode: write ? "generate" : "check", publisher: false, generator: "cargo-dist 0.32.0" }));
  } catch (error) { console.error(JSON.stringify({ status: "fail", errors: [error.message] })); process.exitCode = 1; }
}
